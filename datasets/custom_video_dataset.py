"""
Custom Video Dataset for EVEREST VideoMAE Training

This module provides a PyTorch Dataset class for loading videos from CSV files,
sampling frames, and applying temporal downsampling for VideoMAE training.
"""

import os
import random
import warnings
import torch
from torch.utils.data import Dataset
from torchvision.io import read_video
import numpy as np


class CustomVideoDataset(Dataset):
    """
    Custom dataset for loading videos from CSV files for VideoMAE pretraining.
    
    This dataset:
    - Loads video file paths from a CSV file (one path per line)
    - Uses torchvision.io.read_video to load videos
    - Randomly samples 32 consecutive frames from each video
    - Temporally downsamples with stride 2 to get 16 frames
    - Assumes videos are already 224x224x3 (no resizing)
    - Supports optional random subset sampling via ratio parameter
    
    Args:
        csv_file (str): Path to CSV file containing video file paths (one per line)
        frames_to_sample (int): Number of consecutive frames to sample (default: 32)
        temporal_stride (int): Stride for temporal downsampling (default: 2)
        subset_ratio (float, optional): Ratio of dataset to use (0 < ratio <= 1).
                                       If None, uses full dataset.
        seed (int, optional): Random seed for subset sampling reproducibility
        transform (callable, optional): Optional transform to apply to video frames
    """
    
    def __init__(
        self,
        csv_file,
        frames_to_sample=32,
        temporal_stride=2,
        subset_ratio=None,
        seed=None,
        transform=None
    ):
        self.frames_to_sample = frames_to_sample
        self.temporal_stride = temporal_stride
        self.transform = transform
        
        # Read video paths from CSV file
        if not os.path.exists(csv_file):
            raise FileNotFoundError(f"CSV file not found: {csv_file}")
        
        with open(csv_file, 'r') as f:
            # Read all lines and strip whitespace
            video_paths = [line.strip() for line in f.readlines() if line.strip()]
        
        # Filter out empty paths
        self.video_paths = [path for path in video_paths if path]
        
        if len(self.video_paths) == 0:
            raise ValueError(f"No valid video paths found in {csv_file}")
        
        # Apply subset sampling if specified
        if subset_ratio is not None:
            if not (0 < subset_ratio <= 1):
                raise ValueError(f"subset_ratio must be between 0 and 1, got {subset_ratio}")
            
            if seed is not None:
                random.seed(seed)
            
            subset_size = int(len(self.video_paths) * subset_ratio)
            self.video_paths = random.sample(self.video_paths, subset_size)
            print(f"Using {subset_size} videos ({subset_ratio*100:.1f}% of dataset)")
        
        print(f"Loaded {len(self.video_paths)} video paths from {csv_file}")
    
    def __len__(self):
        """Return the number of videos in the dataset."""
        return len(self.video_paths)
    
    def __getitem__(self, idx):
        """
        Load and process a video sample.
        
        Args:
            idx (int): Index of the video to load
            
        Returns:
            tuple: (video_tensor, mask) where:
                - video_tensor: Tensor of shape [C, T, H, W] = [3, 16, 224, 224]
                - mask: Mask tensor for masking (will be generated by transform)
        """
        video_path = self.video_paths[idx]
        
        # Load video using torchvision
        # Returns: (video_tensor, audio_tensor, info_dict)
        # video_tensor shape: [T, H, W, C] where T is number of frames
        try:
            video, _, info = read_video(video_path, pts_unit='sec')
        except Exception as e:
            warnings.warn(f"Error loading video {video_path}: {e}. Using random index.")
            # Fallback to a random video if loading fails
            idx = random.randint(0, len(self.video_paths) - 1)
            video_path = self.video_paths[idx]
            video, _, info = read_video(video_path, pts_unit='sec')
        
        # video shape: [T, H, W, C] where C=3 for RGB
        num_frames = video.shape[0]
        
        # Check if video has enough frames
        if num_frames < self.frames_to_sample:
            # If video is too short, repeat the last frame
            padding_needed = self.frames_to_sample - num_frames
            last_frame = video[-1:].repeat(padding_needed, 1, 1, 1)
            video = torch.cat([video, last_frame], dim=0)
            num_frames = video.shape[0]
        
        # Randomly sample consecutive frames
        # We need frames_to_sample consecutive frames, then downsample with stride
        max_start = num_frames - self.frames_to_sample
        if max_start < 0:
            start_frame = 0
        else:
            start_frame = random.randint(0, max_start)
        
        # Extract consecutive frames
        sampled_frames = video[start_frame:start_frame + self.frames_to_sample]
        
        # Temporal downsampling with stride
        # This reduces 32 frames to 16 frames (if stride=2)
        downsampled_frames = sampled_frames[::self.temporal_stride]
        
        # Convert from [T, H, W, C] to [C, T, H, W]
        # Permute: [T, H, W, C] -> [T, C, H, W] -> [C, T, H, W]
        video_tensor = downsampled_frames.permute(3, 0, 1, 2).float()
        
        # Normalize to [0, 1] if not already (read_video returns uint8 [0, 255])
        if video_tensor.max() > 1.0:
            video_tensor = video_tensor / 255.0
        
        # Apply transform if provided (for masking, normalization, etc.)
        if self.transform is not None:
            video_tensor, mask = self.transform(video_tensor)
            return video_tensor, mask
        
        # Return video and None mask (mask will be generated elsewhere)
        return video_tensor, None

