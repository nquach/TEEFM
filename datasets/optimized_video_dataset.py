"""
Optimized Video Dataset using LitData StreamingDataset

This module provides a wrapper around litdata's StreamingDataset for loading
optimized video datasets created with litdata.optimize().
"""

import os
import random
import warnings
import torch
from litdata import StreamingDataset, StreamingDataLoader
import numpy as np


class OptimizedVideoDataset:
    """
    Optimized video dataset using LitData StreamingDataset.
    
    This dataset loads videos from an optimized dataset created with litdata.optimize().
    It applies the same frame sampling and temporal downsampling as CustomVideoDataset
    but uses the optimized data format for faster loading.
    
    Args:
        data_dir (str): Path to the optimized dataset directory
        frames_to_sample (int): Number of consecutive frames to sample (default: 32)
        temporal_stride (int): Stride for temporal downsampling (default: 2)
        subset_ratio (float, optional): Ratio of dataset to use (0 < ratio <= 1).
                                       If None, uses full dataset.
        seed (int, optional): Random seed for subset sampling reproducibility
        transform (callable, optional): Optional transform to apply to video frames
    """
    
    def __init__(
        self,
        data_dir,
        frames_to_sample=32,
        temporal_stride=2,
        subset_ratio=None,
        seed=None,
        transform=None
    ):
        self.frames_to_sample = frames_to_sample
        self.temporal_stride = temporal_stride
        self.transform = transform
        
        if not os.path.exists(data_dir):
            raise FileNotFoundError(f"Optimized dataset directory not found: {data_dir}")
        
        # Initialize StreamingDataset from the optimized data directory
        # StreamingDataset.from_data() loads the optimized dataset
        try:
            # Use from_data class method to create StreamingDataset
            self._stream_dataset = StreamingDataset.from_data(data_dir)
        except (AttributeError, TypeError) as e:
            # Fallback: try direct initialization
            try:
                self._stream_dataset = StreamingDataset(data_dir)
            except Exception as e2:
                raise RuntimeError(
                    f"Failed to initialize StreamingDataset from {data_dir}. "
                    f"Tried from_data() and direct initialization. "
                    f"Errors: {e}, {e2}"
                )
        
        # Get the number of items in the dataset
        self._dataset_size = len(self._stream_dataset)
        
        # Apply subset sampling if specified
        if subset_ratio is not None:
            if not (0 < subset_ratio <= 1):
                raise ValueError(f"subset_ratio must be between 0 and 1, got {subset_ratio}")
            
            if seed is not None:
                random.seed(seed)
            
            subset_size = int(self._dataset_size * subset_ratio)
            # For StreamingDataset, we'll handle subset sampling in __getitem__
            self._subset_indices = set(random.sample(range(self._dataset_size), subset_size))
            self._dataset_size = subset_size
            print(f"Using {subset_size} videos ({subset_ratio*100:.1f}% of dataset)")
        else:
            self._subset_indices = None
        
        print(f"Loaded optimized dataset from {data_dir} with {self._dataset_size} items")
    
    def __len__(self):
        """Return the number of videos in the dataset."""
        return self._dataset_size
    
    def __getitem__(self, idx):
        """
        Load and process a video sample from the optimized dataset.
        
        Args:
            idx (int): Index of the video to load
        
        Returns:
            tuple: (video_tensor, mask) where:
                - video_tensor: Tensor of shape [C, T, H, W] = [3, 16, 224, 224]
                - mask: Mask tensor for masking (will be generated by transform)
        """
        # If subset sampling is enabled, map idx to actual dataset index
        if self._subset_indices is not None:
            # Convert idx to actual index in the subset
            actual_indices = sorted(list(self._subset_indices))
            if idx >= len(actual_indices):
                # Wrap around if needed
                idx = idx % len(actual_indices)
            actual_idx = actual_indices[idx]
        else:
            actual_idx = idx
        
        # Load data from StreamingDataset
        # The optimized dataset returns a dict with "path" and "video" keys
        try:
            data = self._stream_dataset[actual_idx]
            
            # Handle different data formats
            if isinstance(data, dict):
                video = data.get('video', data.get('data'))
                if video is None:
                    raise ValueError(f"Video data not found in optimized dataset item {actual_idx}")
            else:
                # If data is directly a tensor
                video = data
            
            # Ensure video is a torch tensor
            if not isinstance(video, torch.Tensor):
                video = torch.tensor(video)
            
        except Exception as e:
            warnings.warn(f"Error loading optimized video at index {actual_idx}: {e}. Using random index.")
            # Fallback to a random index
            if self._subset_indices is not None:
                actual_idx = random.choice(list(self._subset_indices))
            else:
                actual_idx = random.randint(0, len(self._stream_dataset) - 1)
            data = self._stream_dataset[actual_idx]
            if isinstance(data, dict):
                video = data.get('video', data.get('data'))
            else:
                video = data
            if not isinstance(video, torch.Tensor):
                video = torch.tensor(video)
        
        # video shape should be [T, H, W, C] where C=3 for RGB
        if len(video.shape) != 4:
            raise ValueError(f"Expected video shape [T, H, W, C], got {video.shape}")
        
        num_frames = video.shape[0]
        
        # Check if video has enough frames
        if num_frames < self.frames_to_sample:
            # If video is too short, repeat the last frame
            if num_frames == 0:
                raise ValueError(f"Video at index {actual_idx} has 0 frames")
            padding_needed = self.frames_to_sample - num_frames
            last_frame = video[-1:].repeat(padding_needed, 1, 1, 1)
            video = torch.cat([video, last_frame], dim=0)
            num_frames = video.shape[0]
        
        # Randomly sample consecutive frames
        max_start = num_frames - self.frames_to_sample
        if max_start < 0:
            start_frame = 0
        else:
            start_frame = random.randint(0, max_start)
        
        # Extract consecutive frames
        sampled_frames = video[start_frame:start_frame + self.frames_to_sample]
        
        # Temporal downsampling with stride
        downsampled_frames = sampled_frames[::self.temporal_stride]
        
        # Convert from [T, H, W, C] to [C, T, H, W]
        video_tensor = downsampled_frames.permute(3, 0, 1, 2).float()
        
        # Check if video_tensor is empty before calling max()
        if video_tensor.numel() == 0:
            raise ValueError(f"Video at index {actual_idx} resulted in empty tensor after processing")
        
        # Normalize to [0, 1] if not already (read_video returns uint8 [0, 255])
        max_val = video_tensor.max().item() if video_tensor.numel() > 0 else 0.0
        if max_val > 1.0:
            video_tensor = video_tensor / 255.0
        
        # Apply transform if provided (for masking, normalization, etc.)
        if self.transform is not None:
            video_tensor, mask = self.transform(video_tensor)
            return video_tensor, mask
        
        # Return video and None mask (mask will be generated elsewhere)
        return video_tensor, None

